"""Local, isolated PostgreSQL for development.

Uses the PostgreSQL binaries bundled in the `pgserver` pip package that lives
in this project's `.venv` (Python 3.12). Nothing is installed system-wide and
the data lives in `.localdb/` inside the repo (gitignored).

Usage (from repo root):
    .venv\\Scripts\\python scripts/localdb.py setup    # first time: init + start + create DB + write .env
    .venv\\Scripts\\python scripts/localdb.py start
    .venv\\Scripts\\python scripts/localdb.py stop
    .venv\\Scripts\\python scripts/localdb.py status
    .venv\\Scripts\\python scripts/localdb.py reset    # DELETE all local data (asks to confirm)
    .venv\\Scripts\\python scripts/localdb.py psql     # interactive SQL shell
"""

import os
import secrets
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

try:
    from pgserver._commands import POSTGRES_BIN_PATH
except ImportError:
    sys.exit("pgserver not found. Run with .venv\\Scripts\\python (see CLAUDE.md > Local environment).")

ROOT = Path(__file__).resolve().parent.parent
STATE = ROOT / ".localdb"
PGDATA = STATE / "data"
LOGFILE = STATE / "postgres.log"
ENV_FILE = ROOT / ".env"

HOST = "127.0.0.1"
PORT = int(os.environ.get("LOCALDB_PORT", "5433"))  # 5433 avoids clashing with any system Postgres
USER = "skating"
PASSWORD = "skating_local"  # local-only, bound to 127.0.0.1
DBNAME = "skating_school"
URL = f"postgresql://{USER}:{PASSWORD}@{HOST}:{PORT}/{DBNAME}?schema=public"


def exe(name):
    return str(POSTGRES_BIN_PATH / (name + (".exe" if os.name == "nt" else "")))


def run(args, check=True, env=None):
    # stdout/stderr go to files/DEVNULL: piping pg_ctl output can hang on Windows
    # because the detached postmaster inherits the pipe handles.
    return subprocess.run(args, check=check, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, env=env)


def pg_env():
    return {**os.environ, "PGPASSWORD": PASSWORD}


def is_running():
    if not PGDATA.exists():
        return False
    return run([exe("pg_ctl"), "-D", str(PGDATA), "status"], check=False).returncode == 0


def init():
    if (PGDATA / "PG_VERSION").exists():
        return
    STATE.mkdir(exist_ok=True)
    with tempfile.NamedTemporaryFile("w", delete=False, suffix=".pw") as pw:
        pw.write(PASSWORD)
    try:
        run([exe("initdb"), "-D", str(PGDATA), "-U", USER, f"--pwfile={pw.name}",
             "--auth=scram-sha-256", "--encoding=UTF8", "--locale=C"])
    finally:
        os.unlink(pw.name)
    print(f"Initialized data dir: {PGDATA}")


def start():
    if not (PGDATA / "PG_VERSION").exists():
        sys.exit("Not initialized. Run: setup")
    if is_running():
        print(f"Already running on {HOST}:{PORT}")
        return
    r = run([exe("pg_ctl"), "-D", str(PGDATA), "-l", str(LOGFILE), "-w", "-t", "60",
             "-o", f'-p {PORT} -h {HOST}', "start"], check=False)
    if r.returncode != 0:
        sys.exit(f"Failed to start. See log: {LOGFILE}")
    print(f"PostgreSQL running on {HOST}:{PORT}")


def stop():
    if not is_running():
        print("Not running")
        return
    run([exe("pg_ctl"), "-D", str(PGDATA), "-w", "-m", "fast", "stop"])
    print("Stopped")


def create_db():
    exists = subprocess.run(
        [exe("psql"), "-h", HOST, "-p", str(PORT), "-U", USER, "-d", "postgres", "-tAc",
         f"SELECT 1 FROM pg_database WHERE datname='{DBNAME}'"],
        capture_output=True, text=True, env=pg_env(), stdin=subprocess.DEVNULL,
    ).stdout.strip() == "1"
    if not exists:
        run([exe("createdb"), "-h", HOST, "-p", str(PORT), "-U", USER, DBNAME], env=pg_env())
        print(f"Created database: {DBNAME}")


def write_env():
    if ENV_FILE.exists():
        print(".env already exists - left untouched. Local DB URL is:\n  " + URL)
        return
    ENV_FILE.write_text(
        "# LOCAL DEVELOPMENT ONLY - generated by scripts/localdb.py. Never use these values in production.\n"
        f'DATABASE_URL="{URL}"\n'
        f'DIRECT_URL="{URL}"\n'
        f'JWT_SECRET="{secrets.token_urlsafe(48)}"\n'
        'NEXT_PUBLIC_APP_URL="http://localhost:3000"\n',
        encoding="utf-8",
    )
    print("Wrote .env pointing at the local database")


def status():
    print(f"Data dir : {PGDATA} ({'exists' if PGDATA.exists() else 'missing'})")
    print(f"Running  : {is_running()}  ({HOST}:{PORT})")
    print(f"URL      : {URL}")


def reset():
    if input(f"Delete ALL local data in {STATE}? type 'yes': ").strip() != "yes":
        sys.exit("Aborted")
    stop()
    shutil.rmtree(STATE, ignore_errors=True)
    print("Local database deleted. Run: setup")


def psql():
    os.execve(exe("psql"), [exe("psql"), "-h", HOST, "-p", str(PORT), "-U", USER, DBNAME], pg_env())


def setup():
    init()
    start()
    create_db()
    write_env()


COMMANDS = {"setup": setup, "start": start, "stop": stop, "status": status, "reset": reset, "psql": psql}

if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "status"
    if cmd not in COMMANDS:
        sys.exit(f"Unknown command '{cmd}'. Use one of: {', '.join(COMMANDS)}")
    COMMANDS[cmd]()
